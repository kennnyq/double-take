/** Compile published annotation summaries; no runtime fan-out to every tells URL.
 * node scripts/data/demo-quality.ts /path/to/build/feeds/demo.json /path/to/build
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { readTellsFile } from '../../src/annotations/format.ts';

const [feedPath, buildPath] = process.argv.slice(2);
if (!feedPath || !buildPath) throw new Error('Usage: demo-quality.ts <feed.json> <build directory>');
const root = resolve(buildPath);
const feed = JSON.parse(readFileSync(feedPath, 'utf8')) as { clips: { id: string; tells?: string | null }[] };
const summaries: Record<string, unknown> = {};
const visual = new Set(['object_morph', 'continuity', 'anatomy', 'physics', 'lighting']);
for (const clip of feed.clips) {
  if (!clip.tells) continue;
  const path = resolve(root, clip.tells);
  if (relative(root, path).startsWith('..')) throw new Error('Tells path outside build directory');
  const tells = readTellsFile(JSON.parse(readFileSync(path, 'utf8'))).tells.filter((t) => t.seenInFrames !== false);
  summaries[clip.id] = {
    path: clip.tells,
    total: tells.length,
    boxed: tells.filter((t) => t.box).length,
    visual: tells.filter((t) => visual.has(t.category)).length,
    reviewed: tells.filter((t) => t.review === 'verified' || t.review === 'spot_checked').length,
  };
}
writeFileSync(new URL('../../src/data/demoQuality.ts', import.meta.url),
  '// Generated by scripts/data/demo-quality.ts from the published feed and tells.\n' +
  '// Paths fingerprint the annotation revision; signed URL query strings are ignored.\n' +
  `export const DEMO_TELLS = ${JSON.stringify(summaries, null, 2)};\n`);
console.log(`Wrote ${Object.keys(summaries).length} annotation summaries.`);
