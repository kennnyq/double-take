/**
 * Stage 2: a vision-language model looks at sampled frames plus the claims
 * from stage 1 and places each claim in time and space. Its reply is a draft:
 * this module validates it, repairs what can be repaired safely, rejects the
 * rest with a reason, and converts what survives into the app's `Tell`s.
 *
 * Policy (from the PoC: asked blind, the VLMs invented artifacts; asked to
 * localize a named claim, Super VL boxed it correctly):
 *  - Tells must trace to a note or comment claim. Model-only findings are
 *    reported but not published unless `allowModelOnly` is set.
 *  - A box the model says it can't see is dropped; the claim becomes a
 *    box-less step that says so.
 *  - Everything published from here is `review: 'unreviewed'`.
 */
import type { Claim, SourceText } from './claims.ts';
import { CATEGORY_ENUM, normalizeCategory } from './categories.ts';
import type { Box, Confidence, Tell, UnplacedClaim } from './format.ts';
import { bboxToBox, iou } from './geometry.ts';
import { extractJson } from './modelJson.ts';
import { normalizeWindow, parseTime } from './timing.ts';

export interface SampledFrame {
  index: number;
  /** Seconds into the served video. */
  t: number;
  /** Pixel size of the image sent to the model (after any crop and resize). */
  w: number;
  h: number;
}

export interface DraftContext {
  duration: number;
  frames: SampledFrame[];
  /** Frame-space crop applied before sending (letterbox removal), if any. */
  crop?: Box;
  claims: Claim[];
  sources: SourceText[];
  model: string;
  allowModelOnly?: boolean;
  /** Add a box-less step for timed claims the model couldn't place (default true). */
  keepUnplacedClaims?: boolean;
}

export interface Rejected {
  reason: string;
  raw: unknown;
}

export type Coverage = 'boxed' | 'unboxed' | 'unplaced' | 'missing';

export interface DraftResult {
  tells: Tell[];
  /** Claims that can't be shown on the video (no source time, not found by the model). */
  unplaced: UnplacedClaim[];
  rejected: Rejected[];
  issues: string[];
  coverage: Record<string, Coverage>;
}

/**
 * A label in which the model contradicts the claim instead of locating it
 * ("Mouths and eyes look normal", "No Sora logo visible"). Seen in live runs
 * on 2026-11-07; such text must never be shown as a tell.
 */
export function readsAsDenial(label: string): boolean {
  if (/\b(instead of|rather than|not how|fails?|failing|doesn'?t|does not|won'?t)\b/i.test(label)) return false;
  return /\b(no|not|none|nothing|normal|normally|natural|naturally|consistent|consistently|clear|clearly|legible|readable|realistic|correct|correctly|unable|cannot|can'?t|couldn'?t|too small|too blurry)\b/i.test(label);
}

const GENERIC_DESCRIPTION = /^(an? )?ai\b|ai[- ]generated|^(ai )?(tell|artifact)s?$|sora-style/i;

/** A viewer-facing label from the people's own claim (the description, or the quote when the description is generic). */
export function claimLabel(c: Claim): string {
  const base = c.description.length >= 8 && !GENERIC_DESCRIPTION.test(c.description) ? c.description : c.quote;
  return clip(base.charAt(0).toUpperCase() + base.slice(1), LABEL_MAX);
}

export const MAX_TELLS = 5;
/** A before/after pair further apart than this (seconds) is too likely to have moved camera to compare. */
export const MAX_COMPARE_GAP = 3;
const LABEL_MAX = 60;
const DETAIL_MAX = 240;

export const DRAFT_SCHEMA = {
  type: 'object',
  properties: {
    tells: {
      type: 'array',
      maxItems: 8,
      items: {
        type: 'object',
        properties: {
          claim_id: { type: ['string', 'null'] },
          category: { type: 'string', enum: CATEGORY_ENUM },
          label: { type: 'string', maxLength: LABEL_MAX },
          explanation: { type: 'string', maxLength: DETAIL_MAX },
          frame: { type: 'integer' },
          after_frame: { type: ['integer', 'null'] },
          t0: { type: ['number', 'null'] },
          t1: { type: ['number', 'null'] },
          bbox_2d: { type: ['array', 'null'], items: { type: 'integer' }, minItems: 4, maxItems: 4 },
          visible: { type: 'string', enum: ['yes', 'no', 'unsure'] },
          confidence: { type: 'string', enum: ['low', 'medium', 'high'] },
        },
        required: ['claim_id', 'category', 'label', 'explanation', 'frame', 'after_frame', 't0', 't1', 'bbox_2d', 'visible', 'confidence'],
      },
    },
  },
  required: ['tells'],
} as const;

export const DRAFT_SYSTEM = `You check claims that a short video is AI-generated by looking at frames sampled from it.
Each image is preceded by its label: "Frame <n> at <t>s".
For each claim, find the frame where the claimed artifact is clearest and box it.
Rules:
- frame: the frame where the claimed object is clearest. For something that vanishes or changes, use the LAST frame where it still looks normal. bbox_2d = [x1, y1, x2, y2] normalized to 0-1000 on that frame image (x right, y down). Box the object the claim names, tightly. Never box the whole frame.
- after_frame: for something that vanishes, appears or changes, the FIRST frame where it has changed (usually the next frame), so a viewer can compare the same spot; otherwise null.
- visible: "yes" only if you can see the claimed artifact in the frames; "no" if the frames show it is not there; "unsure" otherwise. When "no", set bbox_2d to null.
- t0/t1: seconds where the artifact is visible, using the frame times. Null if unknown.
- label: at most 8 words naming what is wrong, in the claim's terms, e.g. "Dresser vanishes behind her", "Fingernail disappears". Never describe what merely looks fine; if you can't see the problem, set visible "no".
- explanation: one or two plain sentences telling a viewer what to look at.
- claim_id: the claim you checked. Only add a tell with claim_id null if it is unmistakable, and use confidence "low".
- Ignore burned-in captions and on-screen text unless a claim is about them.`;

export function draftPrompt(claims: Claim[], duration: number): string {
  const lines = claims.map(
    (c) =>
      `${c.id}: ${c.description}` +
      (c.t0 !== null ? ` (note says ~${c.t0}s${c.t1 !== null && c.t1 !== c.t0 ? `–${c.t1}s` : ''})` : '') +
      (c.regionHint ? ` [where: ${c.regionHint}]` : '') +
      ` — quote: "${c.quote}"`,
  );
  return `The video is ${duration.toFixed(1)} s long.\nClaims to check:\n${lines.join('\n')}\nAnswer as JSON.`;
}

interface RawTell {
  claim_id?: unknown;
  category?: unknown;
  label?: unknown;
  explanation?: unknown;
  frame?: unknown;
  after_frame?: unknown;
  t0?: unknown;
  t1?: unknown;
  bbox_2d?: unknown;
  visible?: unknown;
  confidence?: unknown;
}

/** Accept the current schema plus the shapes earlier prompts produced (`events`, bare arrays). */
function rawTells(value: unknown, issues: string[]): RawTell[] {
  if (Array.isArray(value)) {
    issues.push('reply is a bare array; read as tells');
    return value as RawTell[];
  }
  const d = value as Record<string, unknown>;
  if (d && Array.isArray(d.tells)) return d.tells as RawTell[];
  if (d && Array.isArray(d.events)) {
    issues.push('reply uses the older "events" shape');
    return (d.events as Record<string, unknown>[]).map((e) => ({
      claim_id: e.claim_id ?? null,
      category: e.category,
      label: e.label ?? e.description,
      explanation: e.description,
      frame: e.frame,
      t0: e.start_s,
      t1: e.end_s,
      bbox_2d: e.bbox_2d,
      visible: e.confirmed === true ? 'yes' : e.confirmed === false ? 'no' : 'unsure',
      confidence: e.confidence,
    }));
  }
  throw new Error('reply has no tells array');
}

const CONF_RANK: Record<Confidence, number> = { low: 0, medium: 1, high: 2 };

function clip(s: string, n: number): string {
  const t = s.replace(/\s+/g, ' ').trim();
  return t.length <= n ? t : `${t.slice(0, n - 1).replace(/\s+\S*$/, '')}…`;
}

function slug(s: string): string {
  return (
    s
      .toLowerCase()
      .normalize('NFKD')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 40) || 'tell'
  );
}

export function validateDraft(reply: unknown, ctx: DraftContext): DraftResult {
  const issues: string[] = [];
  const rejected: Rejected[] = [];
  const { value, repairs } = extractJson(reply);
  issues.push(...repairs.map((r) => `json: ${r}`));
  const list = rawTells(value, issues);

  const claimById = new Map(ctx.claims.map((c) => [c.id, c]));
  const sourceByRef = new Map(ctx.sources.map((s) => [s.ref, s]));
  const frameByIndex = new Map(ctx.frames.map((f) => [f.index, f]));
  const nearestFrame = (t: number) =>
    ctx.frames.reduce<SampledFrame | undefined>((best, f) => (!best || Math.abs(f.t - t) < Math.abs(best.t - t) ? f : best), undefined);

  type Candidate = Tell & { claimId: string | null; rank: number };
  const candidates: Candidate[] = [];
  const unplaced: (UnplacedClaim & { claimId: string })[] = [];
  const unplace = (c: Claim, reason: UnplacedClaim['reason']) => {
    if (unplaced.some((u) => u.claimId === c.id)) return;
    const src = sourceByRef.get(c.ref);
    if (!src) return;
    unplaced.push({
      claimId: c.id,
      quote: c.quote,
      from: src.kind,
      reason,
      ...(src.url ? { url: src.url } : {}),
      ...(src.author && src.kind === 'comment' ? { author: src.author } : {}),
    });
  };

  for (const [i, r] of list.entries()) {
    const tag = `tell ${i}`;
    if (!r || typeof r !== 'object') {
      rejected.push({ reason: `${tag}: not an object`, raw: r });
      continue;
    }
    // --- which claim -------------------------------------------------------
    let claim: Claim | undefined;
    if (typeof r.claim_id === 'string' && r.claim_id) {
      claim = claimById.get(r.claim_id);
      if (!claim) issues.push(`${tag}: unknown claim_id ${JSON.stringify(r.claim_id)}; treated as model-only`);
    }
    // --- text --------------------------------------------------------------
    const explanation = typeof r.explanation === 'string' ? r.explanation.trim() : '';
    let label = typeof r.label === 'string' ? r.label.trim() : '';
    if (!label) label = explanation || claim?.description || '';
    if (!label) {
      rejected.push({ reason: `${tag}: no label or explanation`, raw: r });
      continue;
    }
    if (label.length > LABEL_MAX) issues.push(`${tag}: label shortened`);
    // --- frame -------------------------------------------------------------
    const t0raw = parseTime(r.t0);
    const t1raw = parseTime(r.t1);
    let frame = typeof r.frame === 'number' ? frameByIndex.get(r.frame) : undefined;
    if (r.frame !== undefined && r.frame !== null && !frame) issues.push(`${tag}: frame ${JSON.stringify(r.frame)} wasn't sent`);
    // --- box ---------------------------------------------------------------
    let visible = r.visible === 'yes' || r.visible === 'no' ? r.visible : 'unsure';
    if (visible !== 'no' && readsAsDenial(label)) {
      issues.push(`${tag}: label "${label}" contradicts the claim; treated as not seen`);
      visible = 'no';
    }
    // A denial is the model's opinion, not a tell: speak with the claim's words instead.
    if (visible === 'no' && claim) label = claimLabel(claim);
    let box: Box | undefined;
    if (r.bbox_2d !== null && r.bbox_2d !== undefined) {
      if (visible === 'no') {
        issues.push(`${tag}: model says it can't see this; box dropped`);
      } else {
        if (!frame) {
          // A box without a known frame: tie it to the frame nearest the stated time.
          const t = t0raw ?? claim?.t0 ?? null;
          frame = t !== null ? nearestFrame(t) : undefined;
          if (frame) issues.push(`${tag}: box tied to frame ${frame.index} (nearest ${t}s)`);
        }
        if (!frame) {
          issues.push(`${tag}: box has no frame or time to belong to; box dropped`);
        } else {
          const res = bboxToBox(r.bbox_2d, { pixelSize: { w: frame.w, h: frame.h }, crop: ctx.crop });
          issues.push(...res.notes.map((n) => `${tag}: ${n}`));
          box = res.box ?? undefined;
        }
      }
    }
    // --- before/after ------------------------------------------------------
    let compareT: number | null = null;
    if (box && frame && typeof r.after_frame === 'number') {
      const after = frameByIndex.get(r.after_frame);
      if (!after) issues.push(`${tag}: after_frame ${r.after_frame} wasn't sent; ignored`);
      else if (after.index === frame.index) issues.push(`${tag}: after_frame is the box frame; ignored`);
      else if (Math.abs(after.t - frame.t) > MAX_COMPARE_GAP) issues.push(`${tag}: after_frame is ${Math.abs(after.t - frame.t).toFixed(1)}s from the box frame; too far to compare`);
      else compareT = after.t;
    }
    // --- not found: only the source's own time can place it ---------------
    if (visible === 'no') {
      if (!claim) {
        rejected.push({ reason: `${tag}: model-only and not seen`, raw: r });
        continue;
      }
      if (claim.t0 === null) {
        unplace(claim, 'not_seen');
        issues.push(`${tag}: ${claim.id} not found in the frames and has no time in its source; listed as unplaced`);
        continue;
      }
    }
    // --- time --------------------------------------------------------------
    const win = normalizeWindow(
      visible === 'no'
        ? { t0: claim!.t0, t1: claim!.t1, hasBox: false, duration: ctx.duration }
        : {
            t0: t0raw ?? claim?.t0 ?? null,
            t1: t1raw ?? claim?.t1 ?? null,
            frameT: frame?.t ?? null,
            compareT,
            hasBox: !!box,
            duration: ctx.duration,
          },
    );
    if (!win) {
      rejected.push({ reason: `${tag}: no usable time (t0=${String(r.t0)}, frame=${String(r.frame)})`, raw: r });
      continue;
    }
    issues.push(...win.notes.map((n) => `${tag}: ${n}`));
    // --- provenance --------------------------------------------------------
    let confidence: Confidence = r.confidence === 'high' || r.confidence === 'medium' ? r.confidence : 'low';
    if (visible === 'unsure' && confidence === 'high') confidence = 'medium';
    if (!claim) confidence = 'low';
    const src = claim ? sourceByRef.get(claim.ref) : undefined;
    const tell: Candidate = {
      id: '',
      // A tell inherits its claim's category (already checked against the quote).
      category: claim ? claim.category : normalizeCategory(r.category),
      label: clip(label, LABEL_MAX),
      t0: win.t0,
      t1: win.t1,
      focusT: win.focusT,
      ...(compareT !== null ? { compareT } : {}),
      source: src ? src.kind : 'model',
      review: 'unreviewed',
      confidence,
      seenInFrames: visible === 'yes' ? true : visible === 'no' ? false : undefined,
      model: ctx.model,
      claimId: claim?.id ?? null,
      rank: CONF_RANK[confidence] + (box ? 3 : 0) + (claim ? 6 : 0),
    };
    if (tell.seenInFrames === undefined) delete tell.seenInFrames;
    const detail =
      visible === 'no'
        ? `The ${src?.kind === 'comment' ? 'comment' : 'Community Note'} points to this moment; the model couldn't find it in the frames.`
        : explanation && explanation !== label
          ? explanation
          : claim?.description;
    if (detail) tell.detail = clip(detail, DETAIL_MAX);
    if (box) tell.box = box;
    if (src && claim) {
      tell.evidence = { quote: claim.quote, from: src.kind };
      if (src.url) tell.evidence.url = src.url;
      if (src.author && src.kind === 'comment') tell.evidence.author = src.author;
    }
    if (!claim && !ctx.allowModelOnly) {
      rejected.push({ reason: `${tag}: model-only finding (no note or comment claims it); not published`, raw: r });
      continue;
    }
    candidates.push(tell);
  }

  // --- duplicates: same claim (or same text) at overlapping times ----------
  candidates.sort((a, b) => b.rank - a.rank);
  const kept: Candidate[] = [];
  for (const c of candidates) {
    const dup = kept.find(
      (k) =>
        k.t0 <= c.t1 &&
        c.t0 <= k.t1 &&
        ((k.claimId !== null && k.claimId === c.claimId && (!k.box || !c.box || iou(k.box, c.box) > 0.3)) ||
          k.label.toLowerCase() === c.label.toLowerCase() ||
          (!!k.box && !!c.box && iou(k.box, c.box) > 0.6 && k.category === c.category)),
    );
    if (dup) {
      rejected.push({ reason: `duplicate of "${dup.label}"`, raw: c.label });
      continue;
    }
    kept.push(c);
  }

  // --- claims the model didn't place --------------------------------------
  const coverage: Record<string, Coverage> = {};
  for (const c of ctx.claims) {
    const mine = kept.filter((k) => k.claimId === c.id);
    coverage[c.id] = mine.some((k) => k.box)
      ? 'boxed'
      : mine.length
        ? 'unboxed'
        : unplaced.some((u) => u.claimId === c.id)
          ? 'unplaced'
          : 'missing';
    if (coverage[c.id] !== 'missing' || ctx.keepUnplacedClaims === false) continue;
    const win = c.t0 !== null ? normalizeWindow({ t0: c.t0, t1: c.t1, hasBox: false, duration: ctx.duration }) : null;
    const src = sourceByRef.get(c.ref);
    if (!src) continue;
    if (!win) {
      unplace(c, 'not_checked');
      coverage[c.id] = 'unplaced';
      issues.push(`${c.id}: model didn't check "${c.description}", and the claim has no time; listed as unplaced`);
      continue;
    }
    issues.push(`${c.id}: model didn't place "${c.description}"; added as a box-less step at the claimed time`);
    coverage[c.id] = 'unboxed';
    kept.push({
      id: '',
      category: c.category,
      label: claimLabel(c),
      detail: `The ${src.kind === 'community_note' ? 'Community Note' : 'comment'} says this; the model couldn't place it on a frame.`,
      t0: win.t0,
      t1: win.t1,
      focusT: win.focusT,
      source: src.kind,
      review: 'unreviewed',
      confidence: 'low',
      evidence: { quote: c.quote, from: src.kind, ...(src.url ? { url: src.url } : {}) },
      claimId: c.id,
      rank: 0,
    });
  }

  // --- cap, order, ids ------------------------------------------------------
  const final = kept
    .sort((a, b) => b.rank - a.rank)
    .slice(0, MAX_TELLS)
    .sort((a, b) => a.t0 - b.t0 || a.t1 - b.t1);
  if (kept.length > MAX_TELLS) issues.push(`kept the ${MAX_TELLS} strongest of ${kept.length} tells`);
  const used = new Set<string>();
  const tells = final.map(({ claimId: _c, rank: _r, ...t }) => {
    let id = slug(t.label);
    for (let n = 2; used.has(id); n++) id = `${slug(t.label)}-${n}`;
    used.add(id);
    return { ...t, id };
  });
  return { tells, unplaced: unplaced.map(({ claimId: _c, ...u }) => u), rejected, issues, coverage };
}
